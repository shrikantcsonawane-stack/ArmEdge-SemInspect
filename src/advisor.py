"""Operator advisor: ExecuTorch Llama if configured, else a labelled deterministic fallback.

The advisor only *explains* the vision result; it never alters class/severity/decision.
"""
from __future__ import annotations

import time

from .executorch_advisor import ExecuTorchLlamaAdvisor

FALLBACK_LABEL = "Deterministic rule-based fallback (NOT generated by Llama)"

ACTIONS = {
    "PASS": "Release wafer to next process step. No action required beyond routine sampling.",
    "REVIEW": "Hold wafer and route to a qualified engineer for secondary SEM review before release.",
    "FAIL": "Quarantine wafer, flag lot for disposition, and check upstream process tool for the defect source.",
}


def facts_from_result(r: dict) -> dict:
    """Structured, model-produced facts passed to the advisor (no images, no free text)."""
    return {
        "defect_class": r["pred_class"],
        "confidence": round(r["confidence"], 3),
        "defect_area_pct": None if r["area_pct"] is None else round(r["area_pct"], 3),
        "area_source": r["area_source"],
        "severity": r["severity"],
        "severity_basis": r["severity_reasons"],
        "quality_decision": r["decision"],
        "decision_basis": r["decision_reasons"],
        "secondary_inspection_required": r["secondary_inspection"],
    }


def fallback_text(f: dict) -> str:
    area = ("area not measured (no mask)" if f["defect_area_pct"] is None
            else f"{f['defect_area_pct']:.2f}% of the field of view ({f['area_source']})")
    return "\n".join([
        f"Defect explanation: classifier predicts '{f['defect_class']}' with confidence "
        f"{f['confidence']:.2f}; {area}.",
        f"Severity explanation: {f['severity']} because " + "; ".join(f["severity_basis"]) + ".",
        f"Recommended operator action: {ACTIONS[f['quality_decision']]}",
        "Secondary inspection: " + ("YES - " + "; ".join(f["decision_basis"])
                                    if f["secondary_inspection_required"] else "NO - within configured tolerance."),
    ])


class Advisor:
    def __init__(self, cfg: dict):
        self.cfg = cfg
        self.llama = ExecuTorchLlamaAdvisor(cfg)

    def status(self) -> dict:
        s = self.llama.status()
        s["backend"] = "ExecuTorch Llama 3.2 1B Instruct" if s["configured"] else FALLBACK_LABEL
        return s

    def advise(self, result: dict) -> dict:
        f = facts_from_result(result)
        t0 = time.perf_counter()
        if self.cfg["advisor"].get("backend") == "executorch" and self.llama.status()["configured"]:
            try:
                return {"text": self.llama.generate(f), "source": "ExecuTorch Llama 3.2 1B Instruct",
                        "latency_ms": (time.perf_counter() - t0) * 1000, "facts": f}
            except Exception as e:  # fall through, but report why
                err = f" (Llama call failed: {e})"
        else:
            err = " (ExecuTorch model not configured)"
        return {"text": fallback_text(f), "source": FALLBACK_LABEL + err,
                "latency_ms": (time.perf_counter() - t0) * 1000, "facts": f}
